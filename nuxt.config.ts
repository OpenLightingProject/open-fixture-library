/**
 * The Nuxt 2 sitemap routes() function read the generated register at build
 * time; the Nuxt 4 module resolves `sitemap.urls` during setup, so the same
 * fixture/plugin data is read here. `fixtures/register.json` is generated by
 * `npm run build:register` (which `npm run build` and the baseline script run).
 */
const register = JSON.parse(
  readFileSync(new URL('./fixtures/register.json', import.meta.url), 'utf8'),
) as {
  manufacturers: Record<string, string[]>;
  categories: Record<string, unknown>;
};

type SitemapChangefreq = 'always' | 'hourly' | 'daily' | 'weekly' | 'monthly' | 'yearly' | 'never';
type SitemapUrl = { loc: string; changefreq: SitemapChangefreq; lastmod?: string };

/**
 * Reads a fixture's `meta.lastModifyDate`, following `fixture-redirect.json`
 * files like `fixtureFromRepository` did for the Nuxt 2 sitemap.
 *
 * @param {string} manufacturerKey - The manufacturer key.
 * @param {string} fixtureKey - The fixture key.
 * @returns {string} The ISO last modification date.
 */
function fixtureLastModifyDate(manufacturerKey: string, fixtureKey: string): string {
  const fixture = JSON.parse(
    readFileSync(
      new URL(`./fixtures/${manufacturerKey}/${fixtureKey}.json`, import.meta.url),
      'utf8',
    ),
  ) as {
    $schema?: string;
    redirectTo?: string;
    meta?: { lastModifyDate: string };
  };

  if (fixture.$schema?.endsWith('/fixture-redirect.json') && fixture.redirectTo) {
    const [redirectManufacturerKey, redirectFixtureKey] = fixture.redirectTo.split('/');
    return fixtureLastModifyDate(redirectManufacturerKey, redirectFixtureKey);
  }

  return new Date(fixture.meta!.lastModifyDate).toISOString();
}

/**
 * Builds the same URL list as the Nuxt 2 `sitemap.routes()` oracle.
 *
 * @returns {SitemapUrl[]} The sitemap entries.
 */
function sitemapUrls(): SitemapUrl[] {
  const staticUrls: SitemapUrl[] = [
    { loc: '/', changefreq: 'daily' },
    { loc: '/fixture-editor', changefreq: 'monthly' },
    { loc: '/import-fixture-file', changefreq: 'monthly' },
    { loc: '/manufacturers', changefreq: 'monthly' },
    { loc: '/categories', changefreq: 'monthly' },
    { loc: '/about', changefreq: 'monthly' },
    { loc: '/about/plugins', changefreq: 'monthly' },
    { loc: '/rdm', changefreq: 'yearly' },
    { loc: '/search', changefreq: 'yearly' },
  ];

  const manufacturerUrls = Object.entries(register.manufacturers).flatMap(
    ([manufacturerKey, fixtureKeys]): SitemapUrl[] => [
      { loc: `/${manufacturerKey}`, changefreq: 'weekly' },
      ...fixtureKeys.map(
        (fixtureKey): SitemapUrl => ({
          loc: `/${manufacturerKey}/${fixtureKey}`,
          changefreq: 'monthly',
          lastmod: fixtureLastModifyDate(manufacturerKey, fixtureKey),
        }),
      ),
    ],
  );

  const categoryUrls = Object.keys(register.categories).map(
    (category): SitemapUrl => ({ loc: `/categories/${category}`, changefreq: 'weekly' }),
  );

  const pluginUrls = Object.entries(pluginData.data)
    .filter(([, plugin]) => !plugin.outdated)
    .map(([pluginKey]): SitemapUrl => ({ loc: `/about/plugins/${pluginKey}`, changefreq: 'monthly' }));

  return [...staticUrls, ...manufacturerUrls, ...categoryUrls, ...pluginUrls];
}

